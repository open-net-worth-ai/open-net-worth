// Every tool each directory MCP server exposes, recorded from the vendor's own source or docs
// so Browse & add can show the whole set before anything is connected. Maintainer data, not
// fetched at runtime: `npm run check:connector-tools` flags a list whose package has moved on
// since it was recorded. Once a server is connected, its live list wins (`toolList.ts`).

export interface RecordedTools {
  tools: string[]
  /** The package/server version the list was read from, when it has one. */
  version?: string
  /** When it was recorded (YYYY-MM-DD) — the label for a hosted server with no version. */
  asOf: string
  /** Where the list was read: the source file or docs page. */
  source: string
  /** False when the vendor's docs list tools without claiming it is all of them — shown as
   *  "Example tools", never as the whole set. */
  complete?: boolean
  /** npm or PyPI package to compare `version` against, for a server we can check. */
  pkg?: { registry: 'npm' | 'pypi'; name: string }
}

