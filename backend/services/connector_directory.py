"""The Browse & add directory, as Lucius reads it.

``connector_directory.json`` is a DERIVED snapshot of the frontend's ``catalog.ts`` (generated by
``npm run sync:connector-directory``, pinned by a vitest) — the catalog stays the one source and
this module never edits the file. Everything in it is our own curated, non-secret data.

"Already set up" is joined from live state, not stored: a native connector by id through
``connectors.list_connectors()``, an MCP server by ENDPOINT (the thing being trusted, which a user
cannot rename) exactly as the frontend's ``catalogProvenanceFor`` does. The endpoint is used only
for that comparison and never leaves this module.

ADR ``2026-10-31-lucius-discovers-connectors-from-a-synced-snapshot-and-setup-stays-human``.
"""

from __future__ import annotations

import json
import logging
from functools import lru_cache
from pathlib import Path
from typing import Any, Optional

from backend.core.errors import NotFoundError, did_you_mean

logger = logging.getLogger(__name__)

_SNAPSHOT = Path(__file__).with_name("connector_directory.json")

# A search answers with the best few, not the catalog: filter first, then cap.
MAX_RESULTS = 12

_SETUP_TEXT = {
    "in_app_form": "A setup form in Connectors; the user enters any credentials there",
    "sign_in": "The user signs in to the provider's own page",
    "api_key": "An API key from the provider",
    "none": "No credentials in the form; the server may offer its own login step",
    "manual": "The server's address, supplied by the user",
}


@lru_cache(maxsize=1)
def entries() -> tuple[dict, ...]:
    return tuple(json.loads(_SNAPSHOT.read_text(encoding="utf-8"))["entries"])


# The id that opens the Add custom server form: any MCP server the directory doesn't list.
CUSTOM_SETUP_ID = "custom"

# The directory is curated, not the limit. Asked about Gemini and Binance, Lucius said they "have
# no connector" (live, 2026-10-31) — but any vendor MCP server can be added as a custom one.
BEYOND_DIRECTORY = (
    "The directory is our curated list, not everything the user can connect. An app missing "
    "here may still publish its own MCP server, which the user can add themselves in Browse & "
    "add -> Add custom server (its URL or local command). Never say an app 'has no connector' "
    "from this list alone: say it isn't in the directory, then offer the custom route "
    f"(run_screen_command connectors.open_setup with id '{CUSTOM_SETUP_ID}' opens that form) "
    "or another way in — a statement/CSV import, email ingestion, or recording it by hand."
)


def entry_ids() -> list[str]:
    return [e["id"] for e in entries()]


def unknown_id_message(connector_id: str) -> str:
    close = did_you_mean(connector_id, entry_ids())
    hint = f" Closest: {', '.join(repr(c) for c in close)}." if close else ""
    return (
        f"'{connector_id}' is not a connector in the directory.{hint} "
        "Call search_connector_directory and use an id exactly as it returns, or "
        f"'{CUSTOM_SETUP_ID}' for the Add custom server form."
    )


def _setup(connect: dict) -> dict:
    kind = connect["kind"]
    if kind == "local_command":
        needs = f"Runs on the user's machine and needs {connect['runtime']} installed"
        if connect["env_names"]:
            needs += f"; secrets it reads: {', '.join(connect['env_names'])}"
        return {"method": kind, "needs": needs}
    return {"method": kind, "needs": _SETUP_TEXT[kind]}


def _word_hits(hay: str, query: str) -> int:
    """How many of the query's words appear; a plural finds its singular.

    ANY word is enough to match, and more words matched ranks higher. Requiring every word
    made "bybit webull" match nothing, so Lucius had to search once per name — a search for
    what the user can connect usually names several apps (live test, 2026-10-31). A multi-word
    name still wins its own search: "interactive brokers" puts IBKR (2 hits) above every
    other brokerage (1).
    """
    hay = hay.lower()
    return sum(
        1
        for w in query.lower().split()
        if w in hay or (len(w) > 3 and w.endswith("s") and w[:-1] in hay)
    )


def _installed_state() -> tuple[dict[str, str], Optional[set[str]]]:
    """(native id -> status for every configured connector, endpoints of installed MCP servers, None when unreadable)."""
    from backend.db.mcp_client_store import McpClientStore
    from backend.models.mcp_client import endpoint_of
    from backend.services import connectors as connectors_service

    native = {
        v.id: v.status
        for v in connectors_service.list_connectors()
        if not v.id.startswith("mcp:") and v.status != "not_configured"
    }
    try:
        endpoints = {endpoint_of(c) for c in McpClientStore().all()}
    except Exception:
        # The store builds full configs (tokens included); a malformed row's error text can echo
        # them, so it is logged here and never reaches the model.
        logger.warning("connector directory: installed MCP servers unreadable", exc_info=True)
        return native, None
    return native, {e for e in endpoints if e}


def _live_blurb(connector_id: str) -> str:
    from backend.services import connectors as connectors_service

    try:
        return connectors_service.get_connector(connector_id).short_description
    except NotFoundError:  # a directory row with no live card is simply undescribed
        return ""


def _row(entry: dict, native: dict[str, str], endpoints: Optional[set[str]]) -> dict:
    installed: Optional[bool]
    if entry["mcp"]:
        endpoint = entry.get("endpoint", "")
        installed = None if endpoints is None else bool(endpoint) and endpoint in endpoints
        status: Optional[str] = None
    else:
        status = native.get(entry["id"])
        installed = status is not None
    row: dict[str, Any] = {
        "id": entry["id"],
        "name": entry["name"],
        "publisher": entry["publisher"],
        "verification": entry["verification"],
        "categories": entry["categories"],
        "description": entry.get("sub") or _live_blurb(entry["id"]),
        "installed": installed,
        "setup": _setup(entry["connect"]),
    }
    if status and not entry["mcp"]:
        row["status"] = status
    return row


def search(query: str = "", category: str = "") -> dict:
    query, category = query.strip(), category.strip().lower()
    native, endpoints = _installed_state()
    hits = {
        e["id"]: _word_hits(
            f"{e['name']} {e.get('sub', '')} {e['publisher'] or ''} "
            f"{' '.join(e['categories'])} {' '.join(e['families'])}",
            query,
        )
        if query
        else 0
        for e in entries()
    }
    matched = [
        e
        for e in entries()
        if (not category or category in (c.lower() for c in e["categories"]))
        and (not query or hits[e["id"]] > 0)
    ]
    matched.sort(key=lambda e: (-hits[e["id"]], not e["popular"], e["name"].lower()))
    page = [_row(e, native, endpoints) for e in matched[:MAX_RESULTS]]
    return {"connectors": page, "showing": len(page), "total": len(matched)}


def categories() -> list[str]:
    return sorted({c for e in entries() for c in e["categories"]})
