"""MemoryTopicSummaryStore — the generated one-line Summary of each memory topic.

One row per (section, topic_key) in table ``memory_topic_summaries``: the topic's display name,
its summary, the digest of the facts it was written from, and when. Data access only; deciding
which topics need a summary and what one may say is ``ai.memory_summaries``'s job. Display-only —
never read into a model prompt. The table is checkpoint-excluded (derived, regenerated by the
idle sweep), but writes still fire the hook like every DB store. ADR
``2026-10-25-memory-keeps-only-what-has-no-other-home`` (amendment 8).
"""

from __future__ import annotations

from sqlalchemy import Engine, and_, or_, select
from sqlalchemy import delete as sa_delete
from sqlalchemy import insert as sa_insert

from backend.core.io import fire_db_write_hook
from backend.db.engine import _lock_for_table
from backend.db.tables import memory_topic_summaries as _t

_FIELDS = ("section", "topic_key", "topic", "summary", "facts_digest", "updated_at")


def _pk(section: str, topic_key: str) -> str:
    return f"{section}\x1f{topic_key}"


def _where(keys: list[tuple[str, str]]):
    return or_(*(and_(_t.c.section == s, _t.c.topic_key == k) for s, k in keys))


class MemoryTopicSummaryStore:
    def __init__(self, engine: Engine | None = None):
        self._engine = engine
        self._lock = _lock_for_table(_t.name)

    def _eng(self) -> Engine:
        if self._engine is not None:
            return self._engine
        from backend.db.engine import get_engine

        return get_engine()

    def all(self) -> list[dict]:
        with self._eng().connect() as conn:
            rows = conn.execute(select(_t).order_by(_t.c.section, _t.c.topic_key))
            return [dict(r._mapping) for r in rows]

    def upsert(self, rows: list[dict]) -> int:
        """Write each row whole, replacing the one with the same (section, topic_key)."""
        clean = [{k: r[k] for k in _FIELDS} for r in rows]
        if not clean:
            return 0
        keys = [(r["section"], r["topic_key"]) for r in clean]
        with self._lock, self._eng().begin() as conn:
            before = {
                (r.section, r.topic_key) for r in conn.execute(select(_t).where(_where(keys)))
            }
            fresh = [(_pk(s, k), None) for s, k in keys if (s, k) not in before]
            if fresh:
                fire_db_write_hook(_t.name, fresh, conn=conn)
            self._drop(conn, keys)
            conn.execute(sa_insert(_t), clean)
        return len(clean)

    def delete(self, keys: list[tuple[str, str]]) -> int:
        """Remove the rows for ``keys`` (section, topic_key); returns how many went."""
        if not keys:
            return 0
        with self._lock, self._eng().begin() as conn:
            return self._drop(conn, keys)

    def clear(self) -> int:
        with self._lock, self._eng().begin() as conn:
            return self._drop(conn, None)

    @staticmethod
    def _drop(conn, keys: list[tuple[str, str]] | None) -> int:
        where = None if keys is None else _where(keys)
        existing = conn.execute(select(_t) if where is None else select(_t).where(where)).fetchall()
        if not existing:
            return 0
        fire_db_write_hook(
            _t.name,
            [(_pk(r.section, r.topic_key), dict(r._mapping)) for r in existing],
            conn=conn,
        )
        conn.execute(sa_delete(_t) if where is None else sa_delete(_t).where(where))
        return len(existing)
